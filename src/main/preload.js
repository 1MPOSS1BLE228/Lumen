'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const on = (channel, cb) => {
  const fn = (_e, data) => cb(data);
  ipcRenderer.on(channel, fn);
  return () => ipcRenderer.removeListener(channel, fn);
};

contextBridge.exposeInMainWorld('lumen', {
  init: () => ipcRenderer.invoke('init'),
  setState: (patch) => ipcRenderer.invoke('state:set', patch),
  applyTheme: (id) => ipcRenderer.invoke('theme:apply', id),
  saveTheme: (name) => ipcRenderer.invoke('theme:save', name),
  renameTheme: (id, name) => ipcRenderer.invoke('theme:rename', { id, name }),
  updateTheme: (id) => ipcRenderer.invoke('theme:update', id),
  exportTheme: (id) => ipcRenderer.invoke('theme:export', id),
  importTheme: (code) => ipcRenderer.invoke('theme:import', code),
  surprise: () => ipcRenderer.invoke('theme:surprise'),
  setScenarios: (sc) => ipcRenderer.invoke('scenarios:set', sc),
  resumeScenario: () => ipcRenderer.invoke('scenario:resume'),
  listApps: () => ipcRenderer.invoke('apps:list'),
  hotkeysInfo: () => ipcRenderer.invoke('hotkeys:info'),
  sendScreen: (frame) => ipcRenderer.send('screen:frame', frame),
  copyReport: () => ipcRenderer.invoke('diag:copy'),
  bugReport: (text, hw) => ipcRenderer.invoke('diag:bugreport', text, hw),
  openLog: () => ipcRenderer.invoke('diag:open-log'),
  reportError: (msg) => ipcRenderer.send('renderer:error', msg),
  deleteTheme: (id) => ipcRenderer.invoke('theme:delete', id),
  setDeviceEnabled: (id, enabled) => ipcRenderer.invoke('device:enable', { id, enabled }),
  setColorOrder: (id, zone, order) => ipcRenderer.invoke('device:order', { id, zone, order }),
  setZoneSize: (id, zone, size) => ipcRenderer.invoke('device:size', { id, zone, size }),
  testZone: (id, zone) => ipcRenderer.invoke('device:test', { id, zone }),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  connect: () => ipcRenderer.invoke('conn:connect'),
  disconnect: () => ipcRenderer.invoke('conn:disconnect'),
  pickOpenRGB: () => ipcRenderer.invoke('openrgb:pick'),
  launchOpenRGB: () => ipcRenderer.invoke('openrgb:launch'),
  setEngineAdmin: (on) => ipcRenderer.invoke('engine:admin', on),
  restartEngine: () => ipcRenderer.invoke('engine:restart'),
  flash: (color) => ipcRenderer.invoke('fx:flash', color),
  newRemoteLink: () => ipcRenderer.invoke('remote:newlink'),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  checkHealth: () => ipcRenderer.invoke('health:check'),
  closeConflict: (id) => ipcRenderer.invoke('health:close', id),
  forgetMissing: () => ipcRenderer.invoke('health:forget'),
  photoOptions: (page) => ipcRenderer.invoke('photos:list', page),
  pickPhoto: (item) => ipcRenderer.invoke('photos:pick', item),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  openLightingSettings: () => ipcRenderer.invoke('open:lighting-settings'),
  rescanNative: () => ipcRenderer.invoke('native:rescan'),
  sendAudio: (bands) => ipcRenderer.send('audio:levels', bands),
  setFramesWanted: (on_) => ipcRenderer.send('frames:wanted', !!on_),
  onState: (cb) => on('state', cb),
  onDevices: (cb) => on('devices', cb),
  onConn: (cb) => on('conn', cb),
  onNative: (cb) => on('native', cb),
  onWinTheme: (cb) => on('wintheme', cb),
  onFrames: (cb) => on('frames', cb),
  onScenario: (cb) => on('scenario', cb),
  onSensors: (cb) => on('sensors', cb),
  onHotkeys: (cb) => on('hotkeys', cb),
  onHealth: (cb) => on('health', cb),
  onRemote: (cb) => on('remote', cb),
  onUpdate: (cb) => on('update', cb),
});
